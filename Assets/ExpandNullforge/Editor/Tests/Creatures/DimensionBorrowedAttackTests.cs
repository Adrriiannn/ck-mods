        [Test]
        public void EveryValueInEveryPresetLandsInARealField()
        {
            DimensionMobAsset asset = ScriptableObject.CreateInstance<DimensionMobAsset>();
            try
            {
                SerializedObject serialized = new SerializedObject(asset);
                SerializedProperty combat = serialized.FindProperty("combat");
                Assert.IsNotNull(combat, "the creature has no combat block to pour into");

                // THE TABLE HAS TO BE THERE. Every assertion below is satisfied by a table with no
                // presets in it, and the table is generated by Docs/harvest-borrowed-attacks.sh, so
                // a harvest that wrote a short file would leave this green over nothing.
                Assert.Greater(
                    DimensionBorrowedAttacks.All.Length,
                    400,
                    "The harvested attack table holds almost nothing, so nothing was poured and " +
                    "nothing was checked. The table is 469 presets and is regenerated by " +
                    "Docs/harvest-borrowed-attacks.sh.");

                List<string> lost = new List<string>();
                for (int i = 0; i < DimensionBorrowedAttacks.All.Length; i++)
                {
                    DimensionBorrowedAttackUtility.Apply(
                        combat,
                        DimensionBorrowedAttacks.All[i],
                        lost.Add);
                }

                Assert.IsEmpty(
                    lost,
                    "a preset naming a field that no longer exists loses part of the attack " +
                    "without anyone noticing:\n" + string.Join("\n", lost));
            }
            finally
            {
                Object.DestroyImmediate(asset);
            }
        }

        [Test]
        public void BorrowingAnAttackWritesTheGamesOwnNumbers()
        {
            DimensionBorrowedAttacks.Preset hydra =
                DimensionBorrowedAttacks.ByName("Desert Hydra — its close-up swing");
            Assert.IsNotNull(hydra, "the Desert Hydra's swing is one of the game's own attacks");

            DimensionMobAsset asset = ScriptableObject.CreateInstance<DimensionMobAsset>();
            try
            {
                SerializedObject serialized = new SerializedObject(asset);
                SerializedProperty combat = serialized.FindProperty("combat");
                DimensionBorrowedAttackUtility.Apply(combat, hydra, null);
                serialized.ApplyModifiedPropertiesWithoutUndo();

                Assert.AreEqual(1f, asset.Combat.MeleeWindUp, "measured off the game's own prefab");
                Assert.AreEqual(2f, asset.Combat.MeleeSwingDuration);
                Assert.AreEqual(293, asset.Combat.MeleeDamage);
                Assert.AreEqual(5f, asset.Combat.MeleeReach, "how close it closes to");
                Assert.AreEqual(3f, asset.Combat.MeleeSwingLandsAhead, "how far the swing lands");
                Assert.AreEqual(2f, asset.Combat.MeleeHitRadius);
            }
            finally
            {
                Object.DestroyImmediate(asset);
            }
        }

        [Test]
