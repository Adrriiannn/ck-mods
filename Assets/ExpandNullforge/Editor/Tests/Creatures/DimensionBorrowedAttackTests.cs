        [Test]
        public void EveryAbilityValueInEveryPresetLandsInARealField()
        {
            string[] kinds = { "Charge", "Jump", "Explode", "Ray" };
            DimensionMobAsset asset = ScriptableObject.CreateInstance<DimensionMobAsset>();
            try
            {
                SerializedObject serialized = new SerializedObject(asset);
                SerializedProperty combat = serialized.FindProperty("combat");
                List<string> lost = new List<string>();
                int applied = 0;
                for (int k = 0; k < kinds.Length; k++)
                {
                    DimensionBorrowedAttacks.Preset[] presets =
                        DimensionBorrowedAttacks.OfKind(kinds[k]);
                    for (int i = 0; i < presets.Length; i++)
                    {
                        DimensionBorrowedAttackUtility.Apply(combat, presets[i], lost.Add);
                        applied++;
                    }
                }

                // Four kinds asked for by name. A rename in the table answers all four with an
                // empty array, and nothing would be poured for this to find a lost field in.
                Assert.Greater(
                    applied,
                    0,
                    "None of the four ability kinds (" + string.Join(", ", kinds) + ") matched a " +
                    "preset, so nothing was poured and nothing was checked.");

                Assert.IsEmpty(lost, string.Join("\n", lost));
            }
            finally
            {
                Object.DestroyImmediate(asset);
            }
        }

