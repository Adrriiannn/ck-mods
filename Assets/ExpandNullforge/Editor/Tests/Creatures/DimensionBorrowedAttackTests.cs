        // ---- sounds by name ----

        [Test]
        public void EverySoundInEveryPresetTurnsBackIntoAName()
        {
            DimensionMobAsset asset = ScriptableObject.CreateInstance<DimensionMobAsset>();
            try
            {
                SerializedObject serialized = new SerializedObject(asset);
                SerializedProperty combat = serialized.FindProperty("combat");

                DimensionBorrowedAttacks.Preset[] sounds = DimensionBorrowedAttacks.OfKind("Sounds");
                Assert.Greater(sounds.Length, 100, "the game authored sounds on this many creatures");

                List<string> lost = new List<string>();
                int resolved = 0;
                int unresolvable = 0;
                for (int i = 0; i < sounds.Length; i++)
                {
                    List<string> said = new List<string>();
                    resolved += DimensionBorrowedAttackUtility.Apply(combat, sounds[i], said.Add);
                    for (int s = 0; s < said.Count; s++)
                    {
                        if (said[s].Contains("#sfx:"))
                        {
                            unresolvable++;
                        }
                        else
                        {
                            lost.Add(said[s]);
                        }
                    }
                }

                Assert.IsEmpty(lost, "problems other than a nameless hash:\n" + string.Join("\n", lost));
                Assert.Greater(resolved, 300, "most sounds must come back as readable names");

                // The census when this was built: 6 of ~600 hashes name nothing the game ships.
                // A rise means the name harvest is missing a source, not that the game changed.
                Assert.LessOrEqual(
                    unresolvable,
                    20,
                    "too many sound hashes no longer resolve to names — the name list is incomplete");
            }
            finally
            {
                Object.DestroyImmediate(asset);
            }
        }

