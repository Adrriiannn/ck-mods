        [Test]
        public void ARangedPresetBringsWhatItShootsWithIt()
        {
            DimensionBorrowedAttacks.Preset[] ranged = DimensionBorrowedAttacks.OfKind("Ranged");
            int withAProjectile = 0;
            for (int i = 0; i < ranged.Length; i++)
            {
                for (int v = 0; v < ranged[i].Values.Length; v++)
                {
                    if (ranged[i].Values[v].Path == "projectileItemId" &&
                        !string.IsNullOrEmpty(ranged[i].Values[v].Text))
                    {
                        withAProjectile++;
                        break;
                    }
                }
            }

            Assert.Greater(
                withAProjectile,
                20,
                "a borrowed shot that does not say what it fires is a creature aiming at nothing");
        }

