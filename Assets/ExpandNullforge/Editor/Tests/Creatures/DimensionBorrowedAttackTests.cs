            }
        }

        [Test]
        public void TheSoundNameTableRoundTrips()
        {
            Assert.Greater(DimensionSoundNames.All.Length, 1000);
            Assert.IsTrue(DimensionSoundNames.IsAGameSound("hydraBossBiteAnticipation"));
            Assert.IsFalse(DimensionSoundNames.IsAGameSound("notASound"));
            Assert.AreEqual(0, DimensionSoundNames.Hash(""), "blank is the game's own sound");

            int hash = DimensionSoundNames.Hash("hydraBossBiteAnticipation");
            Assert.AreEqual("hydraBossBiteAnticipation", DimensionSoundNames.NameForHash(hash));
            Assert.IsNull(DimensionSoundNames.NameForHash(123456789));
        }

