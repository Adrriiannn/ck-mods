    /// <summary>
    /// Covers the first door — borrowing one of the game's own attacks whole.
    /// </summary>
    /// <remarks>
    /// <para>
    /// A PRESET FAILS QUIETLY IN THREE WAYS, and none of them looks like a failure. It can name a
    /// field the framework no longer has, and silently leave that part of the attack at a default.
    /// It can land its values without turning the attack on, so the creature carries a perfect
    /// unused shot. And its numbers can be wrong — a preset whose damage is off by a factor is
    /// indistinguishable from one that is right until somebody plays it. These tests hold the first
    /// two; the third is held by the table being generated from the game's own prefabs rather than
    /// typed.
    /// </para>
    /// </remarks>
    public sealed class DimensionBorrowedAttackTests
    {
        private const string TestRoot = "Assets/NullforgeBorrowedTests";

